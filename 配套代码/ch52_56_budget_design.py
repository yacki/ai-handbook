"""Standard-library experiments for mixture accounting and synthetic scaling.
The losses are generated by an explicit toy function, not trained model scores.
"""
import argparse,json,math
from pathlib import Path

def fit_power(xs, ys, floor):
    if not all(x>0 and y>floor for x,y in zip(xs,ys)):
        raise ValueError('positive x and y-floor required')
    lx=[math.log(x) for x in xs];ly=[math.log(y-floor) for y in ys]
    mx=sum(lx)/len(lx);my=sum(ly)/len(ly)
    slope=sum((x-mx)*(y-my) for x,y in zip(lx,ly))/sum((x-mx)**2 for x in lx)
    intercept=my-slope*mx
    return {'floor':floor,'exponent':-slope,'coefficient':math.exp(intercept)}

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--output',type=Path);a=ap.parse_args()
    total=100_000_000
    mixture=[]
    for name,weight,unique,density in [('general',.7,1_000_000_000,1.),('code',.2,50_000_000,1.),('domain',.1,10_000_000,.2)]:
        targets=round(total*weight)
        mixture.append({'domain':name,'target_tokens':targets,'unique_tokens':unique,
                        'equivalent_epochs':targets/unique,'supervision_density':density,
                        'estimated_input_tokens':targets/density})
    xs=[25.,100.,400.];ys=[1.5+4/math.sqrt(n) for n in xs]
    fit=fit_power(xs,ys,1.5)
    wrong_fit=fit_power(xs,ys,1.)
    allocation=[]
    for n in [1.,2.,4.]:
        d=4/n
        allocation.append({'N':int(n*100_000_000),'D':int(d*1_000_000_000),
                           'approx_C':int(6*n*100_000_000*d*1_000_000_000),
                           'synthetic_loss':1.5+.4/math.sqrt(n)+.4/math.sqrt(d)})
    payload={'scope':'arithmetic and synthetic curves, no model training',
             'mixture':mixture,'synthetic_scaling':{'N_in_millions':xs,'losses':ys,
             'known_floor_fit':fit,'wrong_floor_fit':wrong_fit,
             'prediction_N_1600M':fit['floor']+fit['coefficient']/1600**fit['exponent']},
             'same_compute_allocation':allocation}
    s=json.dumps(payload,ensure_ascii=False,indent=2)
    if a.output:a.output.write_text(s+'\n')
    print(s)
if __name__=='__main__':main()
